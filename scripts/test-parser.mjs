// scripts/test-parser.mjs
// Verifica que las 4 copias del parser están sincronizadas con shared/parser.js.
// Uso: node scripts/test-parser.mjs
// Exit code 0 = OK. Exit code 1 = diferencias.

import { readFileSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

let errores = 0;
const ok   = (m) => console.log(`  ✓ ${m}`);
const fail = (m) => { console.error(`  ✗ ${m}`); errores++; };

const shared = readFileSync(resolve(ROOT, 'shared/parser.js'), 'utf-8');
const registro = readFileSync(resolve(ROOT, 'shared/consultas/registro.js'), 'utf-8');
console.log(`shared/parser.js: ${shared.length} bytes\n`);

// ── 1) Copias byte-idénticas ──
console.log('Copias byte-idénticas:');
for (const rel of [
  'public/parser.js',
  'workers/deno-buscar/src/shared/parser.js',
]) {
  try {
    const copy = readFileSync(resolve(ROOT, rel), 'utf-8');
    if (copy === shared) ok(rel);
    else fail(`${rel} DIFIERE de shared/parser.js`);
  } catch (e) {
    fail(`${rel} no existe (${e.message})`);
  }
}

for (const rel of ['public/consultas/registro.js', 'workers/deno-buscar/src/shared/consultas/registro.js']) {
  try {
    if (readFileSync(resolve(ROOT, rel), 'utf-8') === registro) ok(rel);
    else fail(`${rel} DIFIERE del registro`);
  } catch (e) { fail(`${rel} no existe (${e.message})`); }
}

// ── 2) parser-source.js: reconstruir el esperado y comparar ──
const escaped = shared.replace("import { PREFIJOS_CONSULTAS } from './consultas/registro.js';", registro.replaceAll('export const ', 'const '))
  .replace(/\\/g, '\\\\')
  .replace(/`/g, '\\`')
  .replace(/\$\{/g, '\\${');

const expected =
`// AUTO-GENERATED by scripts/sync-parser.mjs
// No editar. Editar shared/parser.js y ejecutar: node scripts/sync-parser.mjs

export const PARSER_SOURCE = \`${escaped}\`;
`;

console.log('\nparser-source.js (string embebido):');
for (const rel of [
  'workers/cf-buscar/src/parser-source.js',
  'workers/deno-buscar/src/parser-source.js',
]) {
  try {
    const actual = readFileSync(resolve(ROOT, rel), 'utf-8');
    if (actual === expected) ok(rel);
    else fail(`${rel} DIFIERE del esperado`);
  } catch (e) {
    fail(`${rel} no existe (${e.message})`);
  }
}

// ── Resultado ──
console.log();
if (errores) {
  console.error(`✗ ${errores} problema(s) detectado(s).`);
  process.exit(1);
}
console.log('✓ Todo sincronizado.');


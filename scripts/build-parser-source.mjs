// scripts/build-parser-source.mjs
// Genera worker/src/parser-source.js a partir de shared/parser.js.
// Se ejecuta antes del deploy (en CI o a mano).

import { readFileSync, writeFileSync, mkdirSync } from 'fs';
import { dirname } from 'path';

const SRC = 'shared/parser.js';
const DST = 'worker/src/parser-source.js';

const src = readFileSync(SRC, 'utf-8');

// Escapar backticks y ${ para que quepa en un template literal
const escaped = src
  .replace(/\\/g, '\\\\')
  .replace(/`/g, '\\`')
  .replace(/\$\{/g, '\\${');

const out = `// AUTO-GENERATED by scripts/build-parser-source.mjs
// No editar. Editar shared/parser.js y volver a ejecutar el script.

export const PARSER_SOURCE = \`${escaped}\`;
`;

mkdirSync(dirname(DST), { recursive: true });
writeFileSync(DST, out, 'utf-8');
console.log(`✓ ${DST} generado (${out.length} bytes)`);
